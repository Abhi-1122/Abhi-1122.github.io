// Wifi as layered arcs so callers can light `bars` 0–3.
const WIFI = [
  pixelPaths([".........", "", "", "", "", "", "", "", "", ".....##.....", ".....##....."].map((r) => r.padEnd(12, "."))),
  pixelPaths(["", "", "", "", "", "", "....####....", "...#....#..."].map((r) => r.padEnd(12, "."))),
  pixelPaths(["", "", "", "...######...", "..#......#..", ".#........#."].map((r) => r.padEnd(12, "."))),
  pixelPaths(["..########..", ".#........#.", "#..........#"]),
];

export function WifiIcon({ bars = 3, ...props }) {
  return (
    <svg viewBox="0 0 12 12" shapeRendering="crispEdges" fill="currentColor" aria-hidden="true" {...props}>
      {WIFI.map((layer, i) => (
        <path key={i} d={layer["#"]} opacity={i === 0 || i <= bars ? 1 : 0.2} />
      ))}
    </svg>
  );
}

// 4 segmented bars; pct ≤ 25 leaves one bar.
export function BatteryIcon({ pct = 86, ...props }) {
  const lit = Math.ceil(Math.max(0, Math.min(100, pct)) / 25);
  return (
    <svg viewBox="0 0 17 8" shapeRendering="crispEdges" fill="currentColor" aria-hidden="true" {...props}>
      <path d="M0 0h15v1H0zM0 7h15v1H0zM0 1h1v6H0zM14 1h1v6h-1zM15 2h2v4h-2z" />
      {[0, 1, 2, 3].map((i) => (
        <rect key={i} x={2 + i * 3} y={2} width={2} height={4} opacity={i < lit ? 1 : 0.15} />
      ))}
    </svg>
  );
}

