// Hand-authored pixel sprites. Each row is a string: "#" ink, "+" half-tone ink, "." empty.
// Custom palettes map extra chars to fills (see A/B buttons). Rendered as crisp SVG runs.

const INK = { "#": { fill: "currentColor" }, "+": { fill: "currentColor", opacity: 0.45 } };

// rows → { char: pathData } using horizontal runs, one <path> per shade.
export function pixelPaths(rows) {
  const d = {};
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      const c = row[x];
      let w = 1;
      while (row[x + w] === c) w++;
      if (c !== ".") d[c] = (d[c] || "") + `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}

export function sprite(rows, colors = INK) {
  const paths = pixelPaths(rows);
  const viewBox = `0 0 ${rows[0].length} ${rows.length}`;
  return function PixelIcon(props) {
    return (
      <svg viewBox={viewBox} shapeRendering="crispEdges" aria-hidden="true" {...props}>
        {Object.entries(paths).map(([c, d]) => (
          <path key={c} d={d} {...colors[c]} />
        ))}
      </svg>
    );
  };
}

